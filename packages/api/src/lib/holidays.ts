function formatYmdInTimeZone(ms: number, timeZone: string): string {
  return new Intl.DateTimeFormat('sv-SE', { timeZone, year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(ms));
}

export function isChinaPublicHoliday(ms: number, timeZone = 'Asia/Shanghai'): boolean {
  return CN_HOLIDAYS.has(formatYmdInTimeZone(ms, timeZone));
}
